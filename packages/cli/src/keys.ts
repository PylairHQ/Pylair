/** `pylair keys init` - wrap `tauri signer generate` (minisign, the update
 * trust anchor of decision 0011 sec. 6): the private key goes to a path the user
 * picks OUTSIDE the project, the pubkey lands in tauri.conf.json's
 * plugins.updater.pubkey, and the user gets the storage instructions the key
 * deserves - losing it means existing installs can never update again.
 */

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { tauriCliEntry } from "./config.js";
import { ui } from "./ui/index.js";
import { askText, type PromptIo } from "./ui/prompts.js";

/** The pubkey value `create-pylair --with-updater` writes, standing in for a
 * real key until `pylair keys init` runs. Keep in step with scaffold.ts. */
export const PUBKEY_PLACEHOLDER = "<generated by pylair keys init>";

/** The pieces of `keys init` a test stubs (process boundary only - every
 * decision above it runs in-process). */
export interface KeysOps {
  /** `node <tauri-cli> signer generate ...`. `inherit` stdio lets the tauri
   * CLI prompt for the password itself on a TTY; `capture` is for the
   * non-interactive `-p` path and returns combined output. */
  generate: (args: string[], mode: "inherit" | "capture", stdin?: string) => number;
  /** Is `path` ignored under the git repo containing `cwd`? - "ignored" only
   * when `git check-ignore` exits 0; "untracked" on 1; "unknown" when there
   * is no repo or no git binary (a path we can't verify counts as tracked). */
  checkIgnored: (path: string, cwd: string) => "ignored" | "untracked" | "unknown";
}

const keysRealOps: KeysOps = {
  generate: (args, mode, stdin) => {
    const r = spawnSync(process.execPath, args, {
      stdio: mode === "inherit" ? "inherit" : ["pipe", "pipe", "pipe"],
      input: stdin,
    });
    return r.status ?? 1;
  },
  checkIgnored: (path, cwd) => {
    const r = spawnSync("git", ["-C", cwd, "check-ignore", "-q", "--", path]);
    if (r.status === 0) return "ignored";
    if (r.status === 1) return "untracked";
    return "unknown";
  },
};

export interface KeysInitOptions {
  appDir: string;
  /** `--key-path`: where the private key is written. Must be outside the
   * project - or git-ignored inside it, verified via `git check-ignore`. */
  keyPath?: string;
  /** `--password`: private-key password; otherwise the env var, a TTY prompt
   * from the tauri CLI itself, or (non-interactive) an empty password. */
  password?: string;
  /** Overwrite an existing pubkey in tauri.conf.json and/or an existing key
   * file. Off by default: a new key needs the OLD one to reach installed
   * copies (the signed rollover update of 0011 sec. 6). */
  force?: boolean;
  env?: NodeJS.ProcessEnv;
  ops?: KeysOps;
  /** Prompt streams for the interactive path/password questions. */
  prompt?: PromptIo;
}

const CONF_ERR_PREFIX = "pylair keys init";

function confPath(appDir: string): string {
  return join(appDir, "src-tauri", "tauri.conf.json");
}

function loadConf(appDir: string): { path: string; conf: Record<string, any> } {
  const path = confPath(appDir);
  if (!existsSync(path))
    throw new Error(`${CONF_ERR_PREFIX}: no src-tauri/tauri.conf.json - run inside a pylair app`);
  try {
    return { path, conf: JSON.parse(readFileSync(path, "utf-8")) };
  } catch (e) {
    throw new Error(`${CONF_ERR_PREFIX}: could not parse ${path}: ${(e as Error).message}`);
  }
}

function defaultKeyPath(appDir: string, product: string): string {
  const safe = product.replace(/[^a-zA-Z0-9._-]+/g, "-") || "app";
  return join(homedir(), ".pylair-keys", `${safe}-updater.key`);
}

/** Refuse a private-key path the user could later commit: inside the app
 * dir it must be git-ignored (verified, not assumed); outside is always
 * fine. Also refuses to clobber an existing key file without --force. */
function assertSafeKeyPath(
  keyPath: string,
  appDir: string,
  force: boolean | undefined,
  ops: KeysOps,
): void {
  const abs = resolve(appDir, keyPath);
  const rel = relative(appDir, abs);
  const inside = rel !== "" && !rel.startsWith("..") && !isAbsolute(rel);
  if (inside) {
    const ignored = ops.checkIgnored(abs, appDir);
    if (ignored !== "ignored")
      throw new Error(
        `${CONF_ERR_PREFIX}: refusing to write the private key inside the project ` +
          `(${rel}) - it would end up in git. ` +
          (ignored === "unknown"
            ? "This directory isn't a git repo, so nothing proves the path is untracked. "
            : "It's not covered by .gitignore. ") +
          "Pick a path outside the project (e.g. the suggested default).",
      );
  }
  if (existsSync(abs) && !force)
    throw new Error(
      `${CONF_ERR_PREFIX}: ${abs} already exists - a fresh key does not reach ` +
        "existing installs (rotation needs the old key, 0011 sec. 6). Pass --force " +
        "to overwrite it anyway.",
    );
}

/** `signer generate` writes `<key>` and `<key>.pub`; the pubkey goes into
 * tauri.conf.json. Password order: --password, env var, then (TTY) the tauri
 * CLI's own prompt with inherited stdio, then (non-interactive) an explicit
 * empty one - piped, the spike proved some CLI builds read stdin instead of
 * honouring `-p ""`. */
function runGenerate(
  entry: string,
  keyPath: string,
  password: string | undefined,
  ops: KeysOps,
): void {
  mkdirSync(dirname(keyPath), { recursive: true });
  const args = [entry, "signer", "generate", "-w", keyPath];
  if (password !== undefined) {
    if (ops.generate([...args, "-p", password], "capture") !== 0)
      throw new Error(`${CONF_ERR_PREFIX}: tauri signer generate failed`);
    return;
  }
  if (ops.generate(args, "inherit") === 0) return;
  // Non-interactive or a build that ignores an absent -p: empty password.
  if (ops.generate([...args, "-p", ""], "capture", "\n") === 0) return;
  throw new Error(`${CONF_ERR_PREFIX}: tauri signer generate failed`);
}

export async function keysInit(opts: KeysInitOptions): Promise<number> {
  const ops = opts.ops ?? keysRealOps;
  const env = opts.env ?? process.env;
  const { path: confFile, conf } = loadConf(opts.appDir);
  const updater = conf.plugins?.updater;
  if (!updater || typeof updater !== "object")
    throw new Error(
      `${CONF_ERR_PREFIX}: ${confFile} has no plugins.updater block - ` +
        "scaffold with `create-pylair --with-updater` or add it first (docs/updates.md)",
    );

  const existing = updater.pubkey;
  const hasKey = typeof existing === "string" && existing !== "" && existing !== PUBKEY_PLACEHOLDER;
  if (hasKey && !opts.force)
    throw new Error(
      `${CONF_ERR_PREFIX}: plugins.updater.pubkey is already set - replacing it ` +
        "strands installed apps (rotation = an update signed by the OLD key, " +
        "0011 sec. 6). Pass --force to overwrite it anyway.",
    );

  const product = typeof conf.productName === "string" ? conf.productName : "app";
  const suggested = defaultKeyPath(opts.appDir, product);
  let keyPath: string;
  if (opts.keyPath) {
    keyPath = resolve(opts.appDir, opts.keyPath);
  } else if (opts.prompt) {
    const answer = await askText(
      opts.prompt,
      `private key path (e.g. ${suggested})`,
    );
    keyPath = resolve(opts.appDir, answer);
  } else {
    throw new Error(
      `${CONF_ERR_PREFIX}: pass --key-path <file> for the private key ` +
        "(a path outside the project; the key must never be committed)",
    );
  }
  assertSafeKeyPath(keyPath, opts.appDir, opts.force, ops);

  const password = opts.password ?? env.TAURI_SIGNING_PRIVATE_KEY_PASSWORD;
  runGenerate(tauriCliEntry(opts.appDir), keyPath, password, ops);

  const pubFile = `${keyPath}.pub`;
  if (!existsSync(pubFile))
    throw new Error(`${CONF_ERR_PREFIX}: signer generate produced no ${pubFile}`);
  const pubkey = readFileSync(pubFile, "utf-8").trim();
  if (!pubkey) throw new Error(`${CONF_ERR_PREFIX}: ${pubFile} is empty`);

  conf.plugins.updater.pubkey = pubkey;
  writeFileSync(confFile, JSON.stringify(conf, null, 2) + "\n");

  ui.ok("pylair keys init: updater key generated");
  ui.line(`  pubkey   -> src-tauri/tauri.conf.json (plugins.updater.pubkey)`);
  ui.line(`  private  -> ${keyPath}`);
  ui.line();
  ui.note(
    [
      "The private key is the update trust anchor - losing it means existing",
      "installs can never update again (reinstall only, 0011 sec. 6):",
      `  - CI secrets: TAURI_SIGNING_PRIVATE_KEY = the file's contents`,
      `                TAURI_SIGNING_PRIVATE_KEY_PASSWORD = the password`,
      "  - keep an offline backup; never commit the key or leave it only on CI",
      "  - rotation ships a new pubkey inside an update signed by the OLD key",
    ].join("\n"),
  );
  return 0;
}
