import { test, describe } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { after } from "node:test";

const bin = fileURLToPath(new URL("../dist/index.js", import.meta.url));

// Pin expectations derive from the vendored compatibility manifest, never
// version literals: the pins PR edits compat.json and these keep passing.
const COMPAT = JSON.parse(
  readFileSync(fileURLToPath(new URL("../src/compat.json", import.meta.url)), "utf8"),
);
const CURRENT = COMPAT.releases.find((r) => r.npm === COMPAT.current);
const dirs = [];
const tmp = () => {
  const d = mkdtempSync(join(tmpdir(), "create-pylair-up-"));
  dirs.push(d);
  return d;
};
after(() => {
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
});

function scaffold(args, cwd) {
  return spawnSync(process.execPath, [bin, ...args], { encoding: "utf8", cwd });
}

const sha = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");

function hashTree(root) {
  const map = {};
  (function walk(p, rel) {
    for (const e of readdirSync(p, { withFileTypes: true })) {
      const c = join(p, e.name), r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(c, r);
      else map[r] = sha(c);
    }
  })(root, "");
  return map;
}

describe("create-pylair --with-updater", () => {
  test("injects the updater plugin, conf block, permission and key gitignore", () => {
    const cwd = tmp();
    const res = scaffold(["up-app", "--with-updater"], cwd);
    assert.equal(res.status, 0, res.stderr);
    const app = join(cwd, "up-app");

    const conf = JSON.parse(readFileSync(join(app, "src-tauri/tauri.conf.json"), "utf-8"));
    assert.equal(conf.bundle.createUpdaterArtifacts, true);
    const up = conf.plugins?.updater;
    assert.ok(up, "plugins.updater missing");
    assert.equal(up.pubkey, "<generated by pylair keys init>");
    assert.ok(up.endpoints.every((e) => e.startsWith("https://")), "endpoints must be https");
    // Each release's own latest.json is its rollback manifest (0011 §6).
    assert.match(up.rollbackUrl, /^https:\/\/.*\{\{version\}\}.*latest\.json$/);
    assert.equal(up.windows?.installMode, "quiet");

    const cargo = readFileSync(join(app, "src-tauri/Cargo.toml"), "utf-8");
    assert.match(cargo, /tauri-plugin-updater = "2"/);
    // pylair pin kept, now carrying the `updater` cargo feature so the
    // host compiles its update machinery (decision 0011 §8 PR 2).
    assert.ok(
      cargo.includes(
        `tauri-plugin-pylair = { version = "=${CURRENT.crate}", features = ["updater"] }`,
      ),
      "updater scaffold keeps the manifest's exact crate pin",
    );

    const cap = JSON.parse(readFileSync(join(app, "src-tauri/capabilities/default.json"), "utf-8"));
    assert.ok(cap.permissions.includes("updater:default"));
    for (const p of [
      "pylair:allow-python-update-check",
      "pylair:allow-python-update-download",
      "pylair:allow-python-update-install",
      "pylair:allow-python-update-relaunch",
    ])
      assert.ok(cap.permissions.includes(p), `capability missing ${p}`);

    const ignore = readFileSync(join(app, ".gitignore"), "utf-8");
    assert.match(ignore, /\*\.key/);

    // The watchdog dispatch is injected at the top of run() — only
    // updater apps carry it (the default scaffold stays byte-identical
    // and compiles against the published crate).
    const lib = readFileSync(join(app, "src-tauri/src/lib.rs"), "utf-8");
    assert.match(
      lib,
      /pub fn run\(\) \{\n    .*\n.*update_watchdog_entry::<tauri::Wry>\(&tauri::generate_context!\(\)\)/s,
    );
    // app.updater() panics without the plugin's managed UpdaterState.
    assert.match(lib, /\.plugin\(tauri_plugin_updater::Builder::new\(\)\.build\(\)\)/);

    // Cargo.lock ships unchanged: it pins the default dep set (incl. the
    // pylair crate); the added plugin resolves on first cargo build. Same
    // app name — the lock records the root package name.
    const flagless = tmp();
    assert.equal(scaffold(["up-app"], flagless).status, 0);
    assert.equal(
      readFileSync(join(app, "src-tauri/Cargo.lock"), "utf-8"),
      readFileSync(join(flagless, "up-app/src-tauri/Cargo.lock"), "utf-8"),
    );
  });

  test("works on the wrap scaffold too", () => {
    const cwd = tmp();
    const res = scaffold(["wrap-up", "--mode", "wrap", "--with-updater"], cwd);
    assert.equal(res.status, 0, res.stderr);
    const conf = JSON.parse(readFileSync(join(cwd, "wrap-up/src-tauri/tauri.conf.json"), "utf-8"));
    assert.ok(conf.plugins?.updater?.pubkey);
    const cargo = readFileSync(join(cwd, "wrap-up/src-tauri/Cargo.toml"), "utf-8");
    assert.match(cargo, /tauri-plugin-updater/);
    assert.match(cargo, /tauri-plugin-pylair = \{ .+features = \["updater"\] \}/);
    const lib = readFileSync(join(cwd, "wrap-up/src-tauri/src/lib.rs"), "utf-8");
    assert.match(lib, /update_watchdog_entry::<tauri::Wry>\(&tauri::generate_context!\(\)\)/);
    assert.match(lib, /\.plugin\(tauri_plugin_updater::Builder::new\(\)\.build\(\)\)/);
  });

  test("default scaffold output is byte-identical to the golden", () => {
    const cwd = tmp();
    const res = scaffold(["my-app"], cwd);
    assert.equal(res.status, 0, res.stderr);
    const golden = JSON.parse(
      readFileSync(new URL("./golden-default.json", import.meta.url), "utf-8"),
    );
    assert.deepEqual(hashTree(join(cwd, "my-app")), golden);
  });

  test("--with-updater + --into fails clearly (existing files are never edited)", () => {
    const cwd = tmp();
    const res = scaffold(["--mode", "wrap", "--into", cwd, "--name", "x-app", "--with-updater"], cwd);
    assert.equal(res.status, 1);
    assert.match(res.stderr, /--with-updater applies to fresh scaffolds/);
  });
});
